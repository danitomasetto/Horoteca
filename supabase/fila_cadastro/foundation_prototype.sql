create table public.watch_intakes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete restrict,
  intake_number bigint not null,
  intake_code text generated always as
    ('H' || case
      when intake_number < 1000 then lpad(intake_number::text, 3, '0')
      else intake_number::text
    end) stored,
  status text not null default 'new' check (status in (
    'new',
    'draft',
    'submitted_for_review_01',
    'review_01_in_progress',
    'review_01_corrections_requested',
    'review_01_approved',
    'submitted_for_review_02',
    'review_02_in_progress',
    'review_02_corrections_requested',
    'review_02_approved',
    'submitted_for_review_03',
    'review_03_in_progress',
    'review_03_corrections_requested',
    'review_03_approved',
    'awaiting_owner_approval',
    'owner_corrections_requested',
    'owner_approved',
    'finalization_ready',
    'finalizing',
    'finalization_failed',
    'completed',
    'cancelled'
  )),
  current_stage text not null default 'intake' check (current_stage in (
    'intake', 'review_01', 'review_02', 'review_03', 'owner',
    'finalization', 'completed', 'cancelled'
  )),
  version integer not null default 1 check (version > 0),
  title text,
  notes text,
  expected_item_count integer check (expected_item_count is null or expected_item_count > 0),
  identified_item_count integer not null default 0 check (identified_item_count >= 0),
  submitted_at timestamptz,
  owner_approved_at timestamptz,
  finalized_at timestamptz,
  cancelled_at timestamptz,
  finalization_key uuid,
  finalization_started_at timestamptz,
  finalization_error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint watch_intakes_number_positive_check check (intake_number > 0),
  constraint watch_intakes_number_key unique (intake_number),
  constraint watch_intakes_code_key unique (intake_code),
  constraint watch_intakes_id_user_key unique (id, user_id),
  constraint watch_intakes_item_counts_check check (
    expected_item_count is null or identified_item_count <= expected_item_count
  ),
  constraint watch_intakes_terminal_dates_check check (
    (status <> 'completed' or finalized_at is not null)
    and (status <> 'cancelled' or cancelled_at is not null)
  )
);

