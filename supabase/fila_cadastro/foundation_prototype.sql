create function horoteca_private.prevent_immutable_audit_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception '% is append-only', tg_table_name using errcode = '55000';
end;
$$;

create function horoteca_private.protect_source_document_identity()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if old.document_role = 'source_a' and (
    new.intake_id is distinct from old.intake_id
    or new.user_id is distinct from old.user_id
    or new.document_role is distinct from old.document_role
    or new.provider is distinct from old.provider
    or new.provider_file_id is distinct from old.provider_file_id
    or new.original_name is distinct from old.original_name
    or new.provider_created_at is distinct from old.provider_created_at
  ) then
    raise exception 'Documento A é logicamente imutável' using errcode = '55000';
  end if;

  if new.document_role = 'approved_b' and old.document_role <> 'approved_b' then
    raise exception 'approved_b exige operação autorizada do proprietário'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create function horoteca_private.assign_intake_identity()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user = 'authenticated' then
    if (select auth.uid()) is null then
      raise exception 'Sessão autenticada obrigatória' using errcode = '28000';
    end if;

    new.user_id := (select auth.uid());
    new.intake_number := nextval('public.watch_intake_number_seq');
    new.status := 'new';
    new.current_stage := 'intake';
    new.version := 1;
    new.owner_approved_at := null;
    new.finalized_at := null;
    new.cancelled_at := null;
    new.finalization_key := null;
    new.finalization_started_at := null;
    new.finalization_error_code := null;
  end if;

  return new;
end;
$$;

create function horoteca_private.protect_intake_control_fields()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if current_user = 'authenticated' and (
    new.user_id is distinct from old.user_id
    or new.intake_number is distinct from old.intake_number
    or new.status is distinct from old.status
    or new.current_stage is distinct from old.current_stage
    or new.version is distinct from old.version
    or new.owner_approved_at is distinct from old.owner_approved_at
    or new.finalized_at is distinct from old.finalized_at
    or new.cancelled_at is distinct from old.cancelled_at
    or new.finalization_key is distinct from old.finalization_key
    or new.finalization_started_at is distinct from old.finalization_started_at
    or new.finalization_error_code is distinct from old.finalization_error_code
  ) then
    raise exception 'Campos de controle exigem operação de transição autorizada'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

